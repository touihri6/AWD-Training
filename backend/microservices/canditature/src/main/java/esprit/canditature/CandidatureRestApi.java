package esprit.canditature;

import esprit.canditature.dto.Candidate;
import esprit.canditature.dto.CandidatureDetails;
import esprit.canditature.dto.CandidatureRequest;
import esprit.canditature.dto.CandidatureResponse;
import esprit.canditature.dto.JobResponse;
import esprit.canditature.feignClient.CandidatClient;
import esprit.canditature.feignClient.JobClient;
import esprit.canditature.service.CandidatureService;
import feign.FeignException;
import feign.codec.DecodeException;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.servlet.support.ServletUriComponentsBuilder;

import java.net.URI;
import java.util.List;

@RestController
@RequestMapping("/mic3/candidature")
public class CandidatureRestApi {

    private final CandidatClient candidatClient;
    private final JobClient jobClient;
    private final CandidatureService candidatureService;


    // Constructor injection: Spring gives the proxy generated by @EnableFeignClients
    public CandidatureRestApi(CandidatClient candidatClient, JobClient jobClient, CandidatureService candidatureService) {
        this.candidatClient = candidatClient;
        this.jobClient = jobClient;
        this.candidatureService = candidatureService;
    }

    @GetMapping("/hello")
    public String sayHello() {
        return "Hello Im microservice 3!";
    }

    /**
     * GET http://localhost:8085/mic3/candidature/candidat/1
     * candidature -> (Eureka: where is CANDIDAT?) -> GET http://<instance>/mic1/candidates/1
     */
    @GetMapping("/candidat/{id}")
    public Candidate getCandidat(@PathVariable("id") Long id) {

        return candidatClient.findById(id);
    }

    @GetMapping("/job/{id}")
    public JobResponse getJob(@PathVariable("id") Long id) {
        return jobClient.findById(id);
    }

    @PostMapping
    public ResponseEntity<CandidatureResponse> create(@Valid @RequestBody CandidatureRequest request) {
        CandidatureResponse created = candidatureService.create(request);
        URI location = ServletUriComponentsBuilder.fromCurrentRequest()
                .path("/{id}").buildAndExpand(created.id()).toUri();
        return ResponseEntity.created(location).body(created);
    }

    @GetMapping
    public List<CandidatureResponse> findAll() {
        return candidatureService.findAll();
    }

    @GetMapping("/{id}")
    public CandidatureResponse findById(@PathVariable("id") Long id) {
        return candidatureService.findById(id);
    }

    @GetMapping("/{id}/details")
    public CandidatureDetails getDetails(@PathVariable("id") Long id) {
        return candidatureService.getDetails(id);
    }

    @DeleteMapping("/{id}")
    public ResponseEntity<Void> delete(@PathVariable("id") Long id) {
        candidatureService.delete(id);
        return ResponseEntity.noContent().build();
    }


    // candidat answered 404 -> Feign throws FeignException.NotFound -> we return 404 too (instead of 500)
    @ExceptionHandler(FeignException.NotFound.class)
    public ResponseEntity<String> candidatNotFound(FeignException.NotFound e) {
        return ResponseEntity.status(HttpStatus.NOT_FOUND).body("Candidat ou job introuvable dans le microservice CANDIDAT ou JOB");
    }

    // candidat answered, but its JSON could not be converted into Candidate -> 502 (not "unavailable")
    @ExceptionHandler(DecodeException.class)
    public ResponseEntity<String> candidatUnreadable(DecodeException e) {
        return ResponseEntity.status(HttpStatus.BAD_GATEWAY)
                .body("Réponse de CANDIDAT ou JOB illisible : " + e.getMessage());
    }

    // candidat stopped or not registered in Eureka -> 503 Service Unavailable
    @ExceptionHandler(FeignException.class)
    public ResponseEntity<String> candidatUnavailable(FeignException e) {
        return ResponseEntity.status(HttpStatus.SERVICE_UNAVAILABLE)
                .body("Microservice CANDIDAT ou JOB indisponible : " + e.getMessage());
    }
}
